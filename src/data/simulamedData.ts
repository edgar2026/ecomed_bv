export function getAlunosSimulaMed(): AlunoSimulaMed[] {
  return alunosSimulaMedData.map(aluno => {
    // Dynamically calculate average across available exams (S1..S5) if not set or to ensure precision
    const examValues = [aluno.s1, aluno.s2, aluno.s3, aluno.s4, aluno.s5]
      .map(v => parseFloat(v))
      .filter(v => !isNaN(v));

    const calcMedia = examValues.length > 0
      ? parseFloat((examValues.reduce((acc, curr) => acc + curr, 0) / examValues.length).toFixed(2))
      : null;

    return {
      ...aluno,
      media: calcMedia !== null ? calcMedia : aluno.media
    };
  });
}
